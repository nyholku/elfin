; Slots are coloured by interference: two registers share one when no
; phase touches both, since the phases never run at the same time.  A
; register listed as pinned keeps its value across a phase boundary and so
; is live everywhere, and never shares.
;
; The N_ prefix keeps these out of the editor's name space: the two share
; one assembly and both wanted a register called SRC.
;
; 151 registers in 62 slots; the largest phase touches 62, which is the
; floor for any allocation.

; Cold registers are marked COLD in the source because they are touched
; a handful of times and never in a loop.  They live in memory instead
; of the variable page: three bytes and one instruction per access, and
; a whole slot given back.

; COLD_AT is main.s's, at the top of the workspace page; COLD_END is
; where they stop, for main.s's guard and the harness's clear.

